const fs = require('node:fs')
const path = require('node:path')
const ts = require('typescript')

// These validation modules have only type imports outside this allowlist.
// Compile the same schemas for the isolated main process; never load a renderer
// Store or a renderer SQL database to validate project storage requests.
const root = path.resolve(__dirname, '..')
const output = path.join(root, 'app-main', 'kernel-validation')
fs.mkdirSync(output, { recursive: true })
const validationModules = [
  'eventCausalityValidation', 'aiRunRequestValidation', 'chapterReviewIdentity', 'chapterReviewCheckpoint',
  'chapterReviewCoverage', 'chapterReviewAcceptance', 'contentReview', 'storyArcValidation', 'inspirationSessions',
  'reconstructionBackupValidation', 'selectionRevision', 'selectionRevisionMetadata', 'projectBackupValidation',
  'entityProvenanceValidation', 'entityProvenanceTypes', 'storyTimeTypes', 'knowledgeSummaryCoverage', 'storyMemory',
  'storyImpactValidation', 'reconstructionCandidates', 'creationDraft', 'characterMemoryIdentity',
  'characterMemoryValidation', 'planningRecovery', 'planningRecoveryValidation', 'editorRecoveryValidation',
  'creationEntryInput', 'storyContract', 'aiJson',
]
for (const name of validationModules) {
  const input = name === 'entityProvenanceTypes' ? path.join('types', 'entityProvenance.ts')
    : name === 'storyTimeTypes' ? path.join('types', 'storyTime.ts')
    : name === 'aiJson' ? path.join('utils', 'aiJson.ts') : path.join('services', name + '.ts')
  const source = fs.readFileSync(path.join(root, 'src', input), 'utf8')
  const result = ts.transpileModule(source, { fileName: name + '.ts', compilerOptions: {
    target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, isolatedModules: true,
  } })
  const destination = path.join(output, name + '.js')
  const content = '// Generated by scripts/prepare-project-kernel.cjs. Do not edit.\n' + result.outputText
    .replace('require("../types/entityProvenance")', 'require("./entityProvenanceTypes")')
    .replace('require("../types/storyTime")', 'require("./storyTimeTypes")')
    .replace('require("../utils/aiJson")', 'require("./aiJson")')
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== content) fs.writeFileSync(destination, content)
}
console.log('主进程项目校验模块已生成。')

// Keep generated validation output exactly aligned with the current module set.
const expectedOutputs = new Set(validationModules.map(name => name + '.js'))
for (const name of fs.readdirSync(output)) {
  if (!name.endsWith('.js') || expectedOutputs.has(name)) continue
  const file = path.join(output, name)
  if (!fs.readFileSync(file, 'utf8').startsWith('// Generated by scripts/prepare-project-kernel.cjs.')) throw new Error('Unexpected file in generated validation directory: ' + name)
  fs.unlinkSync(file)
}
